# 移動而漂移——前一版正是這樣寫錯的（把幾條獨立斷言的功勞算給了三個迴圈）。要知道某條
# 為什麼不在這個清單裡，就把它從 AGENTS.md 拿掉再跑一次本檔。
# 刻意不重列已覆蓋的：重複一份就是第二個真實來源，漂移時兩份各自過期而沒有人會發現。
#
# 本清單是 canonical mapping 的鏡像，兩者分歧時以 ~/.agents 那份為準。它抓的是「AGENTS.md
